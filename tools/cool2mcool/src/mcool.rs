fn required_string_attr(location: &Location, name: &str) -> Result<String> {
    optional_string_attr(location, name)?
        .ok_or_else(|| generation_error(format!("missing required {name} attribute")))
}

fn optional_string_attr(location: &Location, name: &str) -> Result<Option<String>> {
    let attribute = match location.attr(name) {
        Ok(attribute) => attribute,
        Err(_) => return Ok(None),
    };
    if let Ok(value) = attribute.read_scalar::<VarLenUnicode>() {
        return Ok(Some(value.as_str().to_string()));
    }
    if let Ok(value) = attribute.read_scalar::<VarLenAscii>() {
        return Ok(Some(value.as_str().to_string()));
    }
    Err(generation_error(format!(
        "attribute {name} on {} is not a variable-length string",
        location.name()
    )))
}

fn required_u64_attr(location: &Location, name: &str) -> Result<u64> {
    let attribute = location
        .attr(name)
        .map_err(|error| generation_error(format!("missing required {name} attribute: {error}")))?;
    if let Ok(value) = attribute.read_scalar::<u64>() {
        return Ok(value);
    }
    if let Ok(value) = attribute.read_scalar::<u32>() {
        return Ok(value as u64);
    }
    if let Ok(value) = attribute.read_scalar::<i64>() {
        return u64::try_from(value)
            .map_err(|_| generation_error(format!("attribute {name} cannot be negative")));
    }
    let value = attribute.read_scalar::<i32>().map_err(|error| {
        generation_error(format!(
            "attribute {name} on {} is not a supported integer: {error}",
            location.name()
        ))
    })?;
    u64::try_from(value)
        .map_err(|_| generation_error(format!("attribute {name} cannot be negative")))
}

fn sync_completed_partial(partial: &Path) -> Result<()> {
    fs::OpenOptions::new()
        .read(true)
        .write(true)
        .open(partial)
        .and_then(|file| file.sync_all())
        .map_err(|error| {
            generation_error(format!(
                "failed to synchronize completed partial output {}: {error}",
                partial.display()
            ))
        })
}

#[cfg(unix)]
fn apply_input_file_permissions(input: &Path, output: &Path) -> Result<()> {
    use std::os::unix::fs::PermissionsExt;

    let input_mode = fs::metadata(input)
        .map_err(|error| {
            generation_error(format!(
                "failed to read input permissions from {}: {error}",
                input.display()
            ))
        })?
        .permissions()
        .mode();
    let mut output_permissions = fs::metadata(output)
        .map_err(|error| {
            generation_error(format!(
                "failed to read output permissions from {}: {error}",
                output.display()
            ))
        })?
        .permissions();
    output_permissions.set_mode(input_mode & 0o666);
    fs::set_permissions(output, output_permissions).map_err(|error| {
        generation_error(format!(
            "failed to apply input permissions to {}: {error}",
            output.display()
        ))
    })
}

#[cfg(not(unix))]
fn apply_input_file_permissions(_input: &Path, _output: &Path) -> Result<()> {
    Ok(())
}

fn install_partial_output(partial: TempPath, output: &Path, force: bool) -> Result<()> {
    let partial_display = partial.display().to_string();
    let result = if force {
        partial.persist(output)
    } else {
        partial.persist_noclobber(output)
    };
    result.map_err(|error| {
        let operation = if force {
            "atomically replace"
        } else {
            "install without replacing"
        };
        generation_error(format!(
            "failed to {operation} {} with {}: {}",
            output.display(),
            partial_display,
            error.error
        ))
    })
}

fn partial_output_path(output: &Path) -> Result<TempPath> {
    tempfile::Builder::new()
        .prefix(".cool2mcool-partial-")
        .suffix(".mcool")
        .tempfile_in(parent_directory(output))
        .map(|file| file.into_temp_path())
        .map_err(|error| {
            generation_error(format!(
                "could not create a partial output beside {}: {error}",
                output.display()
            ))
        })
}

fn generation_error(message: impl Into<String>) -> Error {
    Error::message(format!("cool2mcool generation error: {}", message.into()))
}

