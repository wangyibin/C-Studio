fn runtime_normalization_memory_budget_bytes(available_bytes: usize) -> usize {
    ((available_bytes as u128) * (RUNTIME_NORMALIZATION_MEMORY_NUMERATOR as u128)
        / (RUNTIME_NORMALIZATION_MEMORY_DENOMINATOR as u128))
        .min(usize::MAX as u128) as usize
}

#[cfg(target_os = "macos")]
#[allow(deprecated)]
fn available_system_memory_bytes() -> Option<usize> {
    static HOST_PORT: std::sync::OnceLock<libc::mach_port_t> = std::sync::OnceLock::new();
    let page_size = unsafe { libc::sysconf(libc::_SC_PAGESIZE) };
    if page_size <= 0 {
        return None;
    }

    let host = *HOST_PORT.get_or_init(|| unsafe { libc::mach_host_self() });
    let mut statistics = std::mem::MaybeUninit::<libc::vm_statistics64_data_t>::zeroed();
    let mut count = libc::HOST_VM_INFO64_COUNT;
    let status = unsafe {
        libc::host_statistics64(
            host,
            libc::HOST_VM_INFO64,
            statistics.as_mut_ptr().cast::<libc::integer_t>(),
            &mut count,
        )
    };
    if status != libc::KERN_SUCCESS {
        return None;
    }
    let statistics = unsafe { statistics.assume_init() };
    let available_pages = u64::from(statistics.free_count)
        .saturating_add(u64::from(statistics.inactive_count))
        .saturating_add(u64::from(statistics.speculative_count));
    usize::try_from(available_pages.saturating_mul(page_size as u64)).ok()
}

#[cfg(target_os = "linux")]
fn available_system_memory_bytes() -> Option<usize> {
    let meminfo = fs::read_to_string("/proc/meminfo").ok()?;
    let kibibytes = meminfo.lines().find_map(|line| {
        let value = line.strip_prefix("MemAvailable:")?.trim();
        value.split_whitespace().next()?.parse::<usize>().ok()
    })?;
    kibibytes.checked_mul(1024)
}

#[cfg(not(any(target_os = "macos", target_os = "linux")))]
fn available_system_memory_bytes() -> Option<usize> {
    None
}

fn estimated_normalization_peak_bytes(pixel_count: usize, bin_count: usize) -> usize {
    // A symmetric CSR needs at most two (u32, f64) entries per source pixel.
    // Pixel columns are read twice in bounded chunks, so no full COO coexists
    // with the CSR. The bin allowance covers row offsets and ICE/KR work vectors.
    pixel_count
        .saturating_mul(24)
        .saturating_add(bin_count.saturating_mul(160))
}

fn ensure_normalization_memory_budget(
    resolution: u64,
    pixel_count: usize,
    bin_count: usize,
) -> Result<()> {
    let estimated_bytes = estimated_normalization_peak_bytes(pixel_count, bin_count);
    let (budget_bytes, availability) = match available_system_memory_bytes() {
        Some(available_bytes) => (
            runtime_normalization_memory_budget_bytes(available_bytes),
            format!(
                "{} MiB currently available; the 80% budget is {} MiB",
                available_bytes / (1024 * 1024),
                runtime_normalization_memory_budget_bytes(available_bytes) / (1024 * 1024),
            ),
        ),
        None => (
            FALLBACK_RUNTIME_NORMALIZATION_MEMORY_BYTES,
            format!(
                "available memory could not be determined; the fallback budget is {} MiB",
                FALLBACK_RUNTIME_NORMALIZATION_MEMORY_BYTES / (1024 * 1024),
            ),
        ),
    };
    if estimated_bytes > budget_bytes {
        return Err(generation_error(format!(
            "resolution {resolution} normalization estimates about {} MiB for {bin_count} bins and {pixel_count} pixels, but {availability}",
            estimated_bytes / (1024 * 1024),
        )));
    }
    Ok(())
}

/// Generate a normalized multi-resolution Cooler from a fixed 1 kb COOL file.
///
/// The output is built in an exclusively created temporary path beside the
/// destination, synchronized, and installed only after every level succeeds.
/// Without `force`, a destination created concurrently is never overwritten.
pub fn generate<F>(
    input: &Path,
    output: &Path,
    options: &GenerationOptions,
    mut progress: F,
) -> Result<GenerationReport>
where
    F: FnMut(Progress),
{
    progress(Progress::ValidatingInput);
    validate_generation_paths(input, output, options.force)?;
    validate_resolution_ladder(&options.resolutions)?;
    validate_kr_min_resolution(options.kr_min_resolution)?;
    validate_compression_level(options.compression_level)?;
    validate_fixed_1k_input(input)?;

    let partial = partial_output_path(output)?;
    let partial_path: &Path = partial.as_ref();
    progress(Progress::Zoomifying {
        resolutions: options.resolutions.clone(),
        aggregation_mode: options.aggregation_mode,
    });
    let zoomify_pool = build_worker_pool(options.threads)?;
    rust_zoomify_with_pool(
        input,
        partial_path,
        &options.resolutions,
        &zoomify_pool,
        ZoomifyExecution::new(
            options.threads,
            options.level_parallelism,
            options.aggregation_mode,
            options.compression_level,
        ),
    )?;
    drop(zoomify_pool);
    if !partial_path.is_file() {
        return Err(generation_error(format!(
            "native Rust zoomify reported success but did not create {}",
            partial_path.display()
        )));
    }
    release_allocator_spare_pages();
    // Keep exactly one bounded Rayon pool alive at a time. Recreating it at
    // the phase boundary preserves one `--threads` budget without retaining
    // zoomify worker-local allocation caches throughout large KR runs.
    let worker_pool = build_worker_pool(options.threads)?;

    for &resolution in &options.resolutions {
        let stored_normalizations =
            stored_normalizations_for_resolution(resolution, options.kr_min_resolution);
        let include_kr = stored_normalizations.contains(&Normalization::Kr);
        let file = open_generated_mcool(partial_path)?;
        let level = generated_resolution_group(&file, resolution)?;
        validate_generated_level(&level, resolution)?;
        let level_input = read_normalization_input(&level, resolution)?;
        let fused_vector_bytes = level_input
            .matrix
            .bin_count()
            .saturating_mul(std::mem::size_of::<f64>())
            .saturating_mul(6);
        if include_kr && fused_vector_bytes <= MAX_FUSED_NORMALIZATION_VECTOR_BYTES {
            let results = compute_stored_normalizations_with_pool(
                &level_input.matrix,
                &level_input.bin_chrom_ids,
                level_input.chromosome_count,
                &worker_pool,
                &|| false,
                |normalization| {
                    progress(Progress::Normalizing {
                        resolution,
                        normalization,
                    });
                },
            )?;

            write_normalization_column(
                &level,
                Normalization::Ice,
                &results.ice.weights,
                options.compression_level,
            )?;
            if !results.ice.converged {
                record_ice_fallback(
                    &level,
                    resolution,
                    results.ice.relative_variance,
                    &mut progress,
                )?;
            }
            write_normalization_column(
                &level,
                Normalization::Kr,
                &results.kr.weights,
                options.compression_level,
            )?;
            annotate_normalization_metric(
                &level,
                Normalization::Kr,
                "cool2mcool_coverage_percentile",
                results.kr.coverage_percentile,
            )?;
            write_normalization_column(
                &level,
                Normalization::Vc,
                &results.vc,
                options.compression_level,
            )?;
            write_normalization_column(
                &level,
                Normalization::VcSqrt,
                &results.vc_sqrt,
                options.compression_level,
            )?;
        } else {
            let LevelNormalizationInput {
                matrix,
                bin_chrom_ids,
                chromosome_count,
            } = level_input;
            let bin_count = matrix.bin_count();
            let perf_enabled = std::env::var("COOL2MCOOL_PERF_LOG").as_deref() == Ok("1");
            let phase_started = std::time::Instant::now();
            let coverage = compute_global_coverage_with_pool(&matrix, &worker_pool, &|| false)?;
            if perf_enabled {
                eprintln!(
                    "COOL2MCOOL_PERF event=normalization_coverage status=complete bins={} source_pixels=shared elapsed_ms={}",
                    bin_count,
                    phase_started.elapsed().as_millis(),
                );
            }

            progress(Progress::Normalizing {
                resolution,
                normalization: Normalization::Ice,
            });
            let phase_started = std::time::Instant::now();
            {
                let ice =
                    compute_ice_from_shared_coverage(&matrix, &coverage, &worker_pool, &|| false)?;
                if perf_enabled {
                    eprintln!(
                        "COOL2MCOOL_PERF event=normalization_ice status=complete bins={} elapsed_ms={}",
                        bin_count,
                        phase_started.elapsed().as_millis(),
                    );
                }
                write_normalization_column(
                    &level,
                    Normalization::Ice,
                    &ice.weights,
                    options.compression_level,
                )?;
                if !ice.converged {
                    record_ice_fallback(&level, resolution, ice.relative_variance, &mut progress)?;
                }
            }

            progress(Progress::Normalizing {
                resolution,
                normalization: Normalization::Vc,
            });
            progress(Progress::Normalizing {
                resolution,
                normalization: Normalization::VcSqrt,
            });
            let phase_started = std::time::Instant::now();
            let (vc, vc_sqrt) = compute_cis_coverage_pair_for_storage(
                &matrix,
                &bin_chrom_ids,
                chromosome_count,
                &|| false,
            )?;
            if perf_enabled {
                eprintln!(
                    "COOL2MCOOL_PERF event=normalization_vc_pair status=complete bins={} elapsed_ms={}",
                    bin_count,
                    phase_started.elapsed().as_millis(),
                );
            }
            write_normalization_column(&level, Normalization::Vc, &vc, options.compression_level)?;
            write_normalization_column(
                &level,
                Normalization::VcSqrt,
                &vc_sqrt,
                options.compression_level,
            )?;
            drop(vc);
            drop(vc_sqrt);
            drop(bin_chrom_ids);

            if include_kr {
                progress(Progress::Normalizing {
                    resolution,
                    normalization: Normalization::Kr,
                });
                let phase_started = std::time::Instant::now();
                let kr = compute_kr_from_shared_coverage_owned(
                    matrix,
                    &coverage,
                    &worker_pool,
                    &|| false,
                )?;
                if perf_enabled {
                    eprintln!(
                        "COOL2MCOOL_PERF event=normalization_kr status=complete bins={} elapsed_ms={}",
                        bin_count,
                        phase_started.elapsed().as_millis(),
                    );
                }
                write_normalization_column(
                    &level,
                    Normalization::Kr,
                    &kr.weights,
                    options.compression_level,
                )?;
                annotate_normalization_metric(
                    &level,
                    Normalization::Kr,
                    "cool2mcool_coverage_percentile",
                    kr.coverage_percentile,
                )?;
            } else {
                remove_normalization_column(&level, Normalization::Kr)?;
            }
        }
        write_level_normalization_manifest(&level, stored_normalizations)?;
        validate_stored_normalizations(&level, resolution, stored_normalizations)?;
        file.flush().map_err(|error| {
            generation_error(format!(
                "failed to flush resolution {resolution} normalizations: {error}"
            ))
        })?;
    }
    let file = open_generated_mcool(partial_path)?;
    write_generation_manifest(&file, &options.resolutions, options.kr_min_resolution)?;
    file.flush()
        .map_err(|error| generation_error(format!("failed to flush generated mcool: {error}")))?;
    drop(file);
    apply_input_file_permissions(input, partial_path)?;
    sync_completed_partial(partial_path)?;

    progress(Progress::Finalizing);
    install_partial_output(partial, output, options.force)?;
    progress(Progress::Complete);

    let kr_resolutions = options
        .resolutions
        .iter()
        .copied()
        .filter(|resolution| *resolution >= options.kr_min_resolution)
        .collect::<Vec<_>>();
    let file_normalizations = stored_normalizations_for_kr(!kr_resolutions.is_empty());
    Ok(GenerationReport {
        output: output.to_path_buf(),
        resolutions: options.resolutions.clone(),
        kr_resolutions,
        kr_min_resolution: options.kr_min_resolution,
        normalization_columns: file_normalizations
            .iter()
            .copied()
            .map(|normalization| normalization_column_spec(normalization).name)
            .collect(),
    })
}

#[cfg(target_os = "macos")]
fn release_allocator_spare_pages() {
    extern "C" {
        fn malloc_zone_pressure_relief(
            zone: *mut libc::malloc_zone_t,
            goal: libc::size_t,
        ) -> libc::size_t;
    }
    // SAFETY: the default malloc zone is process-owned and pressure relief only
    // asks it to return currently unused pages; it cannot invalidate live
    // allocations. Run only at phase boundaries while the shared pool is idle.
    unsafe {
        malloc_zone_pressure_relief(libc::malloc_default_zone(), 0);
    }
}

#[cfg(all(target_os = "linux", target_env = "gnu"))]
fn release_allocator_spare_pages() {
    // SAFETY: malloc_trim releases only free arena pages and does not move live
    // allocations.
    unsafe {
        libc::malloc_trim(0);
    }
}

#[cfg(not(any(target_os = "macos", all(target_os = "linux", target_env = "gnu"))))]
fn release_allocator_spare_pages() {}

fn record_ice_fallback(
    level: &Group,
    resolution: u64,
    relative_variance: f64,
    progress: &mut impl FnMut(Progress),
) -> Result<()> {
    let reason = format!(
        "ICE did not converge within 200 iterations (relative marginal variance {relative_variance:.6e})",
    );
    progress(Progress::NormalizationFallback {
        resolution,
        normalization: Normalization::Ice,
        reason,
    });
    annotate_normalization_fallback(level, Normalization::Ice, "final-iterate-not-converged")?;
    annotate_normalization_metric(
        level,
        Normalization::Ice,
        "cool2mcool_relative_marginal_variance",
        relative_variance,
    )
}

fn validate_generation_paths(input: &Path, output: &Path, force: bool) -> Result<()> {
    if input.extension().and_then(|value| value.to_str()) != Some("cool") {
        return Err(generation_error(format!(
            "input must end with .cool: {}",
            input.display()
        )));
    }
    if output.extension().and_then(|value| value.to_str()) != Some("mcool") {
        return Err(generation_error(format!(
            "output must end with .mcool: {}",
            output.display()
        )));
    }
    if !input.is_file() {
        return Err(generation_error(format!(
            "input cool file does not exist: {}",
            input.display()
        )));
    }
    let output_parent = parent_directory(output);
    if !output_parent.is_dir() {
        return Err(generation_error(format!(
            "output directory does not exist: {}",
            output_parent.display()
        )));
    }
    if output.exists() && !force {
        return Err(generation_error(format!(
            "output already exists (pass --force to replace it): {}",
            output.display()
        )));
    }

    let canonical_input = fs::canonicalize(input).map_err(|error| {
        generation_error(format!(
            "failed to resolve input path {}: {error}",
            input.display()
        ))
    })?;
    let canonical_output = if output.exists() {
        fs::canonicalize(output).map_err(|error| {
            generation_error(format!(
                "failed to resolve output path {}: {error}",
                output.display()
            ))
        })?
    } else {
        let parent = fs::canonicalize(output_parent).map_err(|error| {
            generation_error(format!(
                "failed to resolve output directory {}: {error}",
                output_parent.display()
            ))
        })?;
        parent.join(
            output
                .file_name()
                .ok_or_else(|| generation_error("output path has no filename"))?,
        )
    };
    if canonical_input == canonical_output {
        return Err(generation_error("input and output paths must be different"));
    }
    Ok(())
}

fn parent_directory(path: &Path) -> &Path {
    path.parent()
        .filter(|parent| !parent.as_os_str().is_empty())
        .unwrap_or_else(|| Path::new("."))
}

fn validate_resolution_ladder(resolutions: &[u64]) -> Result<()> {
    if resolutions.is_empty() {
        return Err(generation_error("resolution ladder cannot be empty"));
    }
    for (index, &resolution) in resolutions.iter().enumerate() {
        if resolution == 0 || resolution % BASE_RESOLUTION != 0 {
            return Err(generation_error(format!(
                "resolution {resolution} must be a positive multiple of {BASE_RESOLUTION}"
            )));
        }
        if index > 0 && resolution <= resolutions[index - 1] {
            return Err(generation_error(
                "resolution ladder must be strictly increasing with no duplicates",
            ));
        }
    }
    Ok(())
}

fn validate_kr_min_resolution(kr_min_resolution: u64) -> Result<()> {
    if kr_min_resolution == 0 || kr_min_resolution % BASE_RESOLUTION != 0 {
        return Err(generation_error(format!(
            "KR minimum resolution must be a positive multiple of {BASE_RESOLUTION}, found {kr_min_resolution}"
        )));
    }
    Ok(())
}

fn stored_normalizations_for_kr(include_kr: bool) -> &'static [Normalization] {
    if include_kr {
        &STORED_NORMALIZATIONS_WITH_KR
    } else {
        &STORED_NORMALIZATIONS_WITHOUT_KR
    }
}

fn stored_normalizations_for_resolution(
    resolution: u64,
    kr_min_resolution: u64,
) -> &'static [Normalization] {
    stored_normalizations_for_kr(resolution >= kr_min_resolution)
}

fn validate_fixed_1k_input(path: &Path) -> Result<CoolInputSummary> {
    let file = File::open(path).map_err(|error| {
        generation_error(format!(
            "failed to open input cool file {}: {error}",
            path.display()
        ))
    })?;
    let format = required_string_attr(&file, "format")?;
    if format != "HDF5::Cooler" {
        return Err(generation_error(format!(
            "input format must be HDF5::Cooler, found {format:?}"
        )));
    }
    let bin_type = required_string_attr(&file, "bin-type")?;
    if bin_type != "fixed" {
        return Err(generation_error(format!(
            "input bin-type must be fixed, found {bin_type:?}"
        )));
    }
    let bin_size = required_u64_attr(&file, "bin-size")?;
    if bin_size != BASE_RESOLUTION {
        return Err(generation_error(format!(
            "input bin-size must be {BASE_RESOLUTION}, found {bin_size}"
        )));
    }
    let storage_mode = optional_string_attr(&file, "storage-mode")?
        .unwrap_or_else(|| "symmetric-upper".to_string());
    if storage_mode != "symmetric-upper" {
        return Err(generation_error(format!(
            "input storage-mode must be symmetric-upper, found {storage_mode:?}"
        )));
    }

    let chromosome_count =
        matching_table_lengths(&file, "chroms", &["chroms/name", "chroms/length"])?;
    if chromosome_count == 0 {
        return Err(generation_error("input chroms table is empty"));
    }
    let bin_count =
        matching_table_lengths(&file, "bins", &["bins/chrom", "bins/start", "bins/end"])?;
    if bin_count == 0 {
        return Err(generation_error("input bins table is empty"));
    }
    let pixel_count = matching_table_lengths(
        &file,
        "pixels",
        &["pixels/bin1_id", "pixels/bin2_id", "pixels/count"],
    )?;

    let bin1_offsets =
        read_u64_dataset(&file.dataset("indexes/bin1_offset").map_err(|error| {
            generation_error(format!("input is missing indexes/bin1_offset: {error}"))
        })?)?;
    if bin1_offsets.len() != bin_count + 1
        || bin1_offsets.first().copied() != Some(0)
        || bin1_offsets.last().copied() != Some(pixel_count as u64)
    {
        return Err(generation_error(format!(
            "indexes/bin1_offset must contain {} entries from 0 through {pixel_count}",
            bin_count + 1
        )));
    }
    if bin1_offsets.windows(2).any(|window| window[0] > window[1]) {
        return Err(generation_error(
            "indexes/bin1_offset must be monotonically nondecreasing",
        ));
    }

    let chromosome_offsets =
        read_u64_dataset(&file.dataset("indexes/chrom_offset").map_err(|error| {
            generation_error(format!("input is missing indexes/chrom_offset: {error}"))
        })?)?;
    if chromosome_offsets.len() != chromosome_count + 1
        || chromosome_offsets.first().copied() != Some(0)
        || chromosome_offsets.last().copied() != Some(bin_count as u64)
    {
        return Err(generation_error(format!(
            "indexes/chrom_offset must contain {} entries from 0 through {bin_count}",
            chromosome_count + 1
        )));
    }
    if chromosome_offsets
        .windows(2)
        .any(|window| window[0] > window[1])
    {
        return Err(generation_error(
            "indexes/chrom_offset must be monotonically nondecreasing",
        ));
    }

    Ok(CoolInputSummary {
        bins: bin_count,
        pixels: pixel_count,
    })
}

