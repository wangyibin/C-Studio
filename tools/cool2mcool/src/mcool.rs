fn validate_generated_level(level: &Group, resolution: u64) -> Result<()> {
    let format = required_string_attr(level, "format")?;
    if format != "HDF5::Cooler" {
        return Err(generation_error(format!(
            "resolution {resolution} has invalid format {format:?}"
        )));
    }
    let bin_size = required_u64_attr(level, "bin-size")?;
    if bin_size != resolution {
        return Err(generation_error(format!(
            "resolution group {resolution} declares bin-size {bin_size}"
        )));
    }
    let storage_mode = optional_string_attr(level, "storage-mode")?
        .unwrap_or_else(|| "symmetric-upper".to_string());
    if storage_mode != "symmetric-upper" {
        return Err(generation_error(format!(
            "resolution {resolution} must be symmetric-upper, found {storage_mode:?}"
        )));
    }
    Ok(())
}

fn read_normalization_input(level: &Group, resolution: u64) -> Result<LevelNormalizationInput> {
    let chromosome_count = matching_table_lengths(
        level,
        &format!("resolution {resolution} chromosomes"),
        &["chroms/name", "chroms/length"],
    )?;
    let bin_count = matching_table_lengths(
        level,
        &format!("resolution {resolution} bins"),
        &["bins/chrom", "bins/start", "bins/end"],
    )?;
    let pixel_count = matching_table_lengths(
        level,
        &format!("resolution {resolution} pixels"),
        &["pixels/bin1_id", "pixels/bin2_id", "pixels/count"],
    )?;
    ensure_normalization_memory_budget(resolution, pixel_count, bin_count)?;

    let bin_chrom_dataset = level.dataset("bins/chrom").map_err(|error| {
        generation_error(format!(
            "resolution {resolution} is missing bins/chrom: {error}"
        ))
    })?;
    let mut bin_chrom_ids = Vec::with_capacity(bin_count);
    for start in (0..bin_count).step_by(NORMALIZATION_IO_CHUNK_PIXELS) {
        let end = start
            .saturating_add(NORMALIZATION_IO_CHUNK_PIXELS)
            .min(bin_count);
        let raw = read_u64_dataset_slice(&bin_chrom_dataset, start..end)?;
        if raw.len() != end - start {
            return Err(generation_error(format!(
                "resolution {resolution} bins/chrom changed length while being read"
            )));
        }
        for (offset, chrom) in raw.into_iter().enumerate() {
            let bin = start + offset;
            if chrom >= chromosome_count as u64 {
                return Err(generation_error(format!(
                    "resolution {resolution} bin {bin} references chromosome {chrom} outside {chromosome_count} chromosomes"
                )));
            }
            bin_chrom_ids.push(u32::try_from(chrom).map_err(|_| {
                generation_error(format!(
                    "resolution {resolution} chromosome index {chrom} exceeds u32"
                ))
            })?);
        }
    }

    let bin1_dataset = level.dataset("pixels/bin1_id").map_err(|error| {
        generation_error(format!(
            "resolution {resolution} is missing pixels/bin1_id: {error}"
        ))
    })?;
    let bin2_dataset = level.dataset("pixels/bin2_id").map_err(|error| {
        generation_error(format!(
            "resolution {resolution} is missing pixels/bin2_id: {error}"
        ))
    })?;
    let count_dataset = level.dataset("pixels/count").map_err(|error| {
        generation_error(format!(
            "resolution {resolution} is missing pixels/count: {error}"
        ))
    })?;

    let mut counter = SymmetricCsrCounter::new(bin_count, pixel_count)?;
    let mut previous_pixel = None;
    for start in (0..pixel_count).step_by(NORMALIZATION_IO_CHUNK_PIXELS) {
        let end = start
            .saturating_add(NORMALIZATION_IO_CHUNK_PIXELS)
            .min(pixel_count);
        let (bin1, bin2, counts) =
            read_pixel_chunk(&bin1_dataset, &bin2_dataset, &count_dataset, start..end)?;
        for offset in 0..bin1.len() {
            let pixel_index = start + offset;
            let pixel = (bin1[offset], bin2[offset]);
            if previous_pixel.is_some_and(|previous| previous > pixel) {
                return Err(generation_error(format!(
                    "resolution {resolution} pixels are not sorted at index {pixel_index}"
                )));
            }
            previous_pixel = Some(pixel);
            counter.count_pixel(pixel_index, pixel.0, pixel.1, counts[offset])?;
        }
    }
    let mut builder = counter.into_builder()?;
    for start in (0..pixel_count).step_by(NORMALIZATION_IO_CHUNK_PIXELS) {
        let end = start
            .saturating_add(NORMALIZATION_IO_CHUNK_PIXELS)
            .min(pixel_count);
        let (bin1, bin2, counts) =
            read_pixel_chunk(&bin1_dataset, &bin2_dataset, &count_dataset, start..end)?;
        for offset in 0..bin1.len() {
            builder.push_pixel(start + offset, bin1[offset], bin2[offset], counts[offset])?;
        }
    }
    let matrix = builder.finish()?;
    Ok(LevelNormalizationInput {
        matrix,
        bin_chrom_ids,
        chromosome_count,
    })
}

fn read_pixel_chunk(
    bin1_dataset: &Dataset,
    bin2_dataset: &Dataset,
    count_dataset: &Dataset,
    range: std::ops::Range<usize>,
) -> Result<(Vec<u64>, Vec<u64>, Vec<f64>)> {
    let expected = range.end - range.start;
    let bin1 = read_u64_dataset_slice(bin1_dataset, range.clone())?;
    let bin2 = read_u64_dataset_slice(bin2_dataset, range.clone())?;
    let counts = read_f64_dataset_slice(count_dataset, range)?;
    if bin1.len() != expected || bin2.len() != expected || counts.len() != expected {
        return Err(generation_error(
            "pixel columns changed length while being streamed",
        ));
    }
    Ok((bin1, bin2, counts))
}

