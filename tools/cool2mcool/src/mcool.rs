/// Required base resolution for input COOL files and generated MCOOL ladders.
pub const BASE_RESOLUTION: u64 = 1_000;

const NORMALIZATION_VERSION: u32 = 4;
const KR_ALGORITHM: &str = "whole-assembly-compact-csr-continuation-warm-start-v4";
const RUNTIME_NORMALIZATION_MEMORY_NUMERATOR: usize = 4;
const RUNTIME_NORMALIZATION_MEMORY_DENOMINATOR: usize = 5;
const FALLBACK_RUNTIME_NORMALIZATION_MEMORY_BYTES: usize = 512 * 1024 * 1024;
const NORMALIZATION_IO_CHUNK_PIXELS: usize = 1_000_000;
const MAX_FUSED_NORMALIZATION_VECTOR_BYTES: usize = 128 * 1024 * 1024;

/// Default 10-level resolution ladder generated by [`generate`].
pub const DEFAULT_RESOLUTIONS: &[u64] = &[
    1_000, 5_000, 10_000, 25_000, 50_000, 100_000, 250_000, 500_000, 1_000_000, 2_500_000,
];

const STORED_NORMALIZATIONS_WITH_KR: [Normalization; 4] = [
    Normalization::Ice,
    Normalization::Kr,
    Normalization::Vc,
    Normalization::VcSqrt,
];
const STORED_NORMALIZATIONS_WITHOUT_KR: [Normalization; 3] =
    [Normalization::Ice, Normalization::Vc, Normalization::VcSqrt];

/// Options controlling MCOOL generation and final output installation.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GenerationOptions {
    pub resolutions: Vec<u64>,
    pub threads: usize,
    pub level_parallelism: usize,
    pub aggregation_mode: AggregationMode,
    /// Gzip/deflate level for datasets created by the generator.
    pub compression_level: u8,
    /// Smallest output resolution that receives a true KR vector.
    pub kr_min_resolution: u64,
    pub force: bool,
}

impl Default for GenerationOptions {
    fn default() -> Self {
        Self {
            resolutions: DEFAULT_RESOLUTIONS.to_vec(),
            threads: std::thread::available_parallelism()
                .map_or(1, usize::from)
                .clamp(1, 8),
            level_parallelism: 2,
            aggregation_mode: AggregationMode::Pyramid,
            compression_level: DEFAULT_COMPRESSION_LEVEL,
            kr_min_resolution: BASE_RESOLUTION,
            force: false,
        }
    }
}

/// Progress events emitted synchronously while an output is generated.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Progress {
    ValidatingInput,
    Zoomifying {
        resolutions: Vec<u64>,
        aggregation_mode: AggregationMode,
    },
    Normalizing {
        resolution: u64,
        normalization: Normalization,
    },
    NormalizationFallback {
        resolution: u64,
        normalization: Normalization,
        reason: String,
    },
    Finalizing,
    Complete,
}

