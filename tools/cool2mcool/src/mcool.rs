fn write_normalization_column(
    level: &Group,
    normalization: Normalization,
    multiplicative_weights: &[f64],
    compression_level: u8,
) -> Result<()> {
    validate_compression_level(compression_level)?;
    let spec = normalization_column_spec(normalization);
    let bins = level.group("bins").map_err(|error| {
        generation_error(format!("generated level is missing bins group: {error}"))
    })?;
    let bin_count = dataset_len(&bins.dataset("start").map_err(|error| {
        generation_error(format!("generated level is missing bins/start: {error}"))
    })?)?;
    if multiplicative_weights.len() != bin_count {
        return Err(generation_error(format!(
            "{} normalization has {} weights for {bin_count} bins",
            normalization.as_str(),
            multiplicative_weights.len()
        )));
    }

    let stored = stored_normalization_weights(normalization, multiplicative_weights);
    if bins.link_exists(spec.name) {
        bins.unlink(spec.name).map_err(|error| {
            generation_error(format!(
                "failed to replace bins/{} normalization column: {error}",
                spec.name
            ))
        })?;
    }
    let dataset = bins
        .new_dataset_builder()
        .with_data(stored.as_slice())
        .shuffle()
        .deflate(compression_level)
        .create(spec.name)
        .map_err(|error| {
            generation_error(format!(
                "failed to write bins/{} normalization column: {error}",
                spec.name
            ))
        })?;
    dataset
        .new_attr::<bool>()
        .shape(())
        .create("divisive_weights")
        .and_then(|attribute| attribute.write_scalar(&spec.divisive))
        .map_err(|error| {
            generation_error(format!(
                "failed to mark bins/{} weight convention: {error}",
                spec.name
            ))
        })?;
    let normalization_label = normalization
        .as_str()
        .parse::<VarLenUnicode>()
        .map_err(|error| generation_error(format!("invalid normalization label: {error}")))?;
    dataset
        .new_attr::<VarLenUnicode>()
        .shape(())
        .create("cool2mcool_normalization")
        .and_then(|attribute| attribute.write_scalar(&normalization_label))
        .map_err(|error| {
            generation_error(format!(
                "failed to annotate bins/{} normalization column: {error}",
                spec.name
            ))
        })?;
    let scope = normalization_scope(normalization)
        .parse::<VarLenUnicode>()
        .map_err(|error| generation_error(format!("invalid normalization scope: {error}")))?;
    dataset
        .new_attr::<VarLenUnicode>()
        .shape(())
        .create("cool2mcool_scope")
        .and_then(|attribute| attribute.write_scalar(&scope))
        .map_err(|error| {
            generation_error(format!(
                "failed to annotate bins/{} normalization scope: {error}",
                spec.name
            ))
        })?;
    dataset
        .new_attr::<u32>()
        .shape(())
        .create("cool2mcool_normalization_version")
        .and_then(|attribute| attribute.write_scalar(&NORMALIZATION_VERSION))
        .map_err(|error| {
            generation_error(format!(
                "failed to annotate bins/{} normalization version: {error}",
                spec.name
            ))
        })?;
    Ok(())
}

fn remove_normalization_column(level: &Group, normalization: Normalization) -> Result<()> {
    let spec = normalization_column_spec(normalization);
    let bins = level.group("bins").map_err(|error| {
        generation_error(format!("generated level is missing bins group: {error}"))
    })?;
    if bins.link_exists(spec.name) {
        bins.unlink(spec.name).map_err(|error| {
            generation_error(format!(
                "failed to remove bins/{} normalization column: {error}",
                spec.name
            ))
        })?;
    }
    Ok(())
}

fn stored_normalization_weights(
    normalization: Normalization,
    multiplicative_weights: &[f64],
) -> Vec<f64> {
    let spec = normalization_column_spec(normalization);
    multiplicative_weights
        .iter()
        .map(|weight| {
            if !weight.is_finite() || *weight <= 0.0 {
                f64::NAN
            } else if spec.divisive {
                1.0 / *weight
            } else {
                *weight
            }
        })
        .collect()
}

fn normalization_column_spec(normalization: Normalization) -> NormalizationColumnSpec {
    match normalization {
        Normalization::Ice => NormalizationColumnSpec {
            name: "weight",
            divisive: false,
        },
        Normalization::Kr => NormalizationColumnSpec {
            name: "KR",
            divisive: true,
        },
        Normalization::Vc => NormalizationColumnSpec {
            name: "VC",
            divisive: true,
        },
        Normalization::VcSqrt => NormalizationColumnSpec {
            name: "VC_SQRT",
            divisive: true,
        },
        Normalization::Raw => panic!("raw contacts do not have a stored normalization column"),
    }
}

fn normalization_scope(normalization: Normalization) -> &'static str {
    match normalization {
        Normalization::Ice | Normalization::Kr => "whole-assembly",
        Normalization::Vc | Normalization::VcSqrt => "chromosome-cis",
        Normalization::Raw => "raw",
    }
}

fn validate_stored_normalizations(
    level: &Group,
    resolution: u64,
    expected_normalizations: &[Normalization],
) -> Result<()> {
    let bins = level.group("bins").map_err(|error| {
        generation_error(format!(
            "resolution {resolution} is missing bins after normalization: {error}"
        ))
    })?;
    let bin_count = dataset_len(&bins.dataset("start").map_err(|error| {
        generation_error(format!(
            "resolution {resolution} is missing bins/start after normalization: {error}"
        ))
    })?)?;
    for normalization in STORED_NORMALIZATIONS_WITH_KR {
        let spec = normalization_column_spec(normalization);
        if !expected_normalizations.contains(&normalization) {
            if bins.link_exists(spec.name) {
                return Err(generation_error(format!(
                    "resolution {resolution} unexpectedly contains bins/{}",
                    spec.name
                )));
            }
            continue;
        }
        let dataset = bins.dataset(spec.name).map_err(|error| {
            generation_error(format!(
                "resolution {resolution} is missing bins/{} after normalization: {error}",
                spec.name
            ))
        })?;
        let observed_len = dataset_len(&dataset)?;
        if observed_len != bin_count {
            return Err(generation_error(format!(
                "resolution {resolution} bins/{} has {observed_len} values for {bin_count} bins",
                spec.name
            )));
        }
        let divisive = dataset
            .attr("divisive_weights")
            .and_then(|attribute| attribute.read_scalar::<bool>())
            .map_err(|error| {
                generation_error(format!(
                    "resolution {resolution} bins/{} is missing its weight convention: {error}",
                    spec.name
                ))
            })?;
        if divisive != spec.divisive {
            return Err(generation_error(format!(
                "resolution {resolution} bins/{} has the wrong weight convention",
                spec.name
            )));
        }
        let scope = dataset
            .attr("cool2mcool_scope")
            .and_then(|attribute| attribute.read_scalar::<VarLenUnicode>())
            .map_err(|error| {
                generation_error(format!(
                    "resolution {resolution} bins/{} is missing its normalization scope: {error}",
                    spec.name
                ))
            })?;
        if scope.as_str() != normalization_scope(normalization) {
            return Err(generation_error(format!(
                "resolution {resolution} bins/{} declares unexpected scope {:?}",
                spec.name,
                scope.as_str(),
            )));
        }
    }
    Ok(())
}

fn normalization_manifest(normalizations: &[Normalization]) -> Result<VarLenUnicode> {
    normalizations
        .iter()
        .map(|normalization| normalization.as_str())
        .collect::<Vec<_>>()
        .join(",")
        .parse::<VarLenUnicode>()
        .map_err(|error| generation_error(format!("invalid normalization manifest: {error}")))
}

fn write_level_normalization_manifest(
    level: &Group,
    normalizations: &[Normalization],
) -> Result<()> {
    let manifest = normalization_manifest(normalizations)?;
    level
        .new_attr::<VarLenUnicode>()
        .shape(())
        .create("cool2mcool_normalizations")
        .and_then(|attribute| attribute.write_scalar(&manifest))
        .map_err(|error| {
            generation_error(format!(
                "failed to write level cool2mcool_normalizations manifest: {error}"
            ))
        })
}

fn write_generation_manifest(
    file: &File,
    resolutions: &[u64],
    kr_min_resolution: u64,
) -> Result<()> {
    let has_kr = resolutions
        .iter()
        .any(|resolution| *resolution >= kr_min_resolution);
    let normalizations = normalization_manifest(stored_normalizations_for_kr(has_kr))?;
    file.new_attr::<VarLenUnicode>()
        .shape(())
        .create("cool2mcool_normalizations")
        .and_then(|attribute| attribute.write_scalar(&normalizations))
        .map_err(|error| {
            generation_error(format!(
                "failed to write cool2mcool_normalizations manifest: {error}"
            ))
        })?;
    file.new_attr::<u64>()
        .shape(())
        .create("cool2mcool_kr_min_resolution")
        .and_then(|attribute| attribute.write_scalar(&kr_min_resolution))
        .map_err(|error| {
            generation_error(format!(
                "failed to write cool2mcool KR minimum resolution: {error}"
            ))
        })?;
    file.new_attr::<u32>()
        .shape(())
        .create("cool2mcool_normalization_version")
        .and_then(|attribute| attribute.write_scalar(&NORMALIZATION_VERSION))
        .map_err(|error| {
            generation_error(format!(
                "failed to write cool2mcool normalization version: {error}"
            ))
        })?;
    if has_kr {
        let kr_algorithm = KR_ALGORITHM
            .parse::<VarLenUnicode>()
            .map_err(|error| generation_error(format!("invalid KR algorithm manifest: {error}")))?;
        file.new_attr::<VarLenUnicode>()
            .shape(())
            .create("cool2mcool_kr_algorithm")
            .and_then(|attribute| attribute.write_scalar(&kr_algorithm))
            .map_err(|error| {
                generation_error(format!(
                    "failed to write cool2mcool KR algorithm manifest: {error}"
                ))
            })?;
    }
    Ok(())
}

fn matching_table_lengths(location: &Group, label: &str, paths: &[&str]) -> Result<usize> {
    let mut expected = None;
    for path in paths {
        let dataset = location
            .dataset(path)
            .map_err(|error| generation_error(format!("{label} is missing {path}: {error}")))?;
        let length = dataset_len(&dataset)?;
        match expected {
            Some(expected) if expected != length => {
                return Err(generation_error(format!(
                    "{label} columns have different lengths: expected {expected}, {path} has {length}"
                )));
            }
            None => expected = Some(length),
            _ => {}
        }
    }
    Ok(expected.unwrap_or(0))
}

fn dataset_len(dataset: &Dataset) -> Result<usize> {
    let shape = dataset.shape();
    if shape.len() != 1 {
        return Err(generation_error(format!(
            "dataset {} must be one-dimensional, found shape {shape:?}",
            dataset.name()
        )));
    }
    Ok(shape[0])
}

fn read_u64_dataset(dataset: &Dataset) -> Result<Vec<u64>> {
    if let Ok(values) = dataset.read_1d::<u64>() {
        return Ok(values.to_vec());
    }
    if let Ok(values) = dataset.read_1d::<u32>() {
        return Ok(values.iter().map(|value| *value as u64).collect());
    }
    if let Ok(values) = dataset.read_1d::<i64>() {
        return values
            .iter()
            .map(|value| {
                u64::try_from(*value).map_err(|_| {
                    generation_error(format!(
                        "dataset {} contains negative value {value}",
                        dataset.name()
                    ))
                })
            })
            .collect();
    }
    let values = dataset.read_1d::<i32>().map_err(|error| {
        generation_error(format!(
            "dataset {} is not a supported integer type: {error}",
            dataset.name()
        ))
    })?;
    values
        .iter()
        .map(|value| {
            u64::try_from(*value).map_err(|_| {
                generation_error(format!(
                    "dataset {} contains negative value {value}",
                    dataset.name()
                ))
            })
        })
        .collect()
}

